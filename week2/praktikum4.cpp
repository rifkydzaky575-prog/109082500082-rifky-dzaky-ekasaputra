#include <iostream>
using namespace std;
int main() {
    int penjumlahan, pengurangan, perkalian, pembagian;
    cout << "Masukkan nilai penjumlahan: ";
    cin >> penjumlahan;
    cout << "Masukkan nilai pengurangan: ";
    cin >> pengurangan;
    cout << "Masukkan nilai perkalian: ";
    cin >> perkalian;
    cout << "Masukkan nilai pembagian: ";
    cin >> pembagian;
    cout << "Hasil penjumlahan: " << penjumlahan << endl
            << "Hasil pengurangan: " << pengurangan << endl
            << "Hasil perkalian: " << perkalian << endl
            << "Hasil pembagian: " << pembagian << endl;
    return 0;
}